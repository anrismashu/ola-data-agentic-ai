from typing import Annotated, Literal
from pydantic import BaseModel, Field
from langgraph.graph.message import add_messages # FIX: LangGraph's smart message reducer

class AgentSchema(BaseModel):
    # FIX: applied add_messages
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="List of messages to be processed by the agent",
    )
    user_question: str = Field(..., description="User's original question")
    curated_ques: str = Field(default="", description="Curated user question")
    prompt_querry_context: str = Field(
        default="", description="A detailed prompt with SQL DB context"
    )
    generated_sql_query: str = Field(
        default="", description="The SQL query generated by LLM"
    )  
    is_safe: Literal["Yes", "No"] = Field(
        default="No", description="Indicates whether the generated query is safe"
    )  
    comments: str = Field(
        default="", description="Comments about the generated SQL query"
    )
    sql_querry_execution_result: str = Field(
        default="", description="The result of the query execution"
    )
    final_answer: str = Field(
        default="", description="The final answer generated by LLM"
    )


class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(
        ..., description="Indicates whether the query is safe to execute"
    )
    comments: str = Field(
        ..., description="Reasoning or explanation of the judgment"
    )
    
 
class ETLAgentSchema(BaseModel):
    # FIX: applied add_messages and default_factory
    messages: Annotated[list, add_messages] = Field(
        default_factory=list, 
        description="List of messages to be processed by the ETL agent"
    )
    
class RouterSchema(BaseModel):
    answer: Literal["sql", "etl", "chat"] = Field(
        ...,
        description="Indicates whether the user's message should go to the sql agent, etl agent, or general chat",
    )
    comments: str = Field(
        ..., description="Reasoning or explanation of the judgment"
    )
class DataAgentSchema(BaseModel):
    # FIX: applied add_messages and default_factory
    messages: Annotated[list, add_messages] = Field(
        default_factory=list, 
        description="List of messages to be processed by the DataAgent agent"
    )
    # FIX: Changed from `...` to `default=""` to prevent startup crashes
    route_response: str = Field(
        default="", 
        description="The response from the router indicating what agent is chosen/picked"
    )